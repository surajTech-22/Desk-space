    internal static readonly string[] Categories=Shortcuts.Select(x=>x.Category)
        .Distinct(StringComparer.OrdinalIgnoreCase)
        .OrderBy(x=>x,StringComparer.OrdinalIgnoreCase).ToArray();
    internal static (string Keys,string Operation,string Category)[] Find(
        string text,string category="All")
    {
        var q=(text??"").Trim();
        return Shortcuts.Where(x=>
            (category=="All" || x.Category.Equals(category,StringComparison.OrdinalIgnoreCase)) &&
            (q.Length==0 || x.Keys.Contains(q,StringComparison.OrdinalIgnoreCase) ||
            x.Operation.Contains(q,StringComparison.OrdinalIgnoreCase) ||
            x.Category.Contains(q,StringComparison.OrdinalIgnoreCase))).ToArray();
    }
